//! End-to-end cover for C3's sensitivity gate, driven through the LIBRARY rather than
//! by spawning `target/release/sensitivity`.
//!
//! Calling the binary as a subprocess would make this test depend on a build artefact
//! existing, on `cargo test` and `cargo build` having used the same profile, and would
//! give back a string instead of the report structure — three ways to be green while the
//! gate is broken. `src/bin/sensitivity.rs` is a thin CLI over
//! `universe::gpu::sensitivity`, and this file exercises that module on the same inputs
//! the binary would hand it.
//!
//! # The fixture
//!
//! There is no `UWAV` recording in this repository (checked 11/09: no `*.uwav` outside
//! `target/`), and a recording can only be produced by `gpu_evolve --record-wave`, which
//! needs the GPU the PRD forbids agents from touching. So the wave is a committed
//! fixture, `tests/fixtures/sensitivity_synthetic_cpu.uwav`, and it is GENERATED BY
//! CODE: [`build_fixture_bytes`] rebuilds it byte for byte, and
//! `the_committed_fixture_matches_the_generator` fails the moment the file and the
//! generator disagree. To regenerate it after an intentional change, run
//! `cargo test --release --test sensitivity_gate -- --ignored`.
//!
//! **What the fixture is NOT.** Its 192 channels are a closed-form sinusoid bank
//! (`sensitivity::synthetic_wave`), not a lap, and its three command columns are the
//! CPU `SovereignEngine`'s output, not `BrainGpu`'s — hence `_cpu` in the name. It
//! proves WIRING (a perturbed block can reach the command) and nothing about behaviour
//! on a real track. It must never be fed to `src/bin/screen.rs`, whose whole point is
//! scoring against commands the real brain kernel actually issued.

use std::io::Write as _;

use universe::config::iara::brain::SENSORY_WAVE_SIZE;
use universe::gpu::dof::{DEFAULT_GENE_THRESHOLD, dof_by_block};
use universe::gpu::evolution::Genome;
use universe::gpu::genome_io::{load_genome, save_genome};
use universe::gpu::sensitivity::{
    DEFAULT_DELTAS, Verdict, groups, replay_open_loop, run_gate, synthetic_wave,
};
use universe::gpu::wave_record::{self, WaveConfig};

const FIXTURE: &str = "tests/fixtures/sensitivity_synthetic_cpu.uwav";
/// The genome half of the fixture pair, so `sensitivity` can be run against a known
/// input with no setup at all:
/// `./target/release/sensitivity --genoma tests/fixtures/sensitivity_genome.bin
///  --onda tests/fixtures/sensitivity_synthetic_cpu.uwav`.
/// Written by `save_genome`, read back by the canonical `load_genome` — a gate nobody
/// can run without first producing an artefact is a gate nobody runs.
const GENOME_FIXTURE: &str = "tests/fixtures/sensitivity_genome.bin";
/// Small on purpose: 48 ticks × 195 f32 ≈ 37 KB on disk, and the gate replays the wave
/// once per (group, δ, sign) arm — 45 replays at the default two deltas.
const FIXTURE_TICKS: usize = 48;
/// Seed of the fixture genome. `Genome::random` is deterministic per seed
/// (`evolution.rs:450-454`), so this one genome is the same on every machine.
const FIXTURE_SEED: u64 = 0xC3_5E_1751;

/// The runtime configuration this fixture was produced under. Every flag is set to what
/// the CPU replay actually does, never to what `gpu_evolve` would have done: the four
/// P1.7 mechanisms are `off` because `SovereignEngine` has none of them, and
/// `neuromod_regioes` is 0 because the M4 conductor lives in `gpu_evolve/context.rs` and
/// no library replay runs it. A header that claimed otherwise would be the exact bug the
/// `UWAV` header was introduced to remove.
fn fixture_config() -> WaveConfig {
    WaveConfig {
        dt: 1.0 / 64.0,
        out_beta: 0.85,
        out_gain: 2.0,
        norm_l2_by_std: 0,
        noise_sigma: 0.0,
        dropout_prob: 0.0,
        mem_off: 1,
        period_off: 1,
        threshold_off: 1,
        activation_off: 1,
        neuromod_regioes: 0,
        brain_skip: 1,
        pilot_active: 0,
    }
}

/// Rebuilds the committed fixture from scratch. Pure: same bytes on every call.
fn build_fixture_bytes() -> Vec<u8> {
    let cfg = fixture_config();
    let waves = synthetic_wave(FIXTURE_TICKS);
    let genome = Genome::random(FIXTURE_SEED);
    let intents = replay_open_loop(&genome, &waves, cfg.dt);

    let mut out: Vec<u8> = Vec::new();
    wave_record::write_header(&mut out, &cfg).expect("writing to a Vec cannot fail");
    for (t, intent) in intents.iter().enumerate() {
        let row = &waves[t * SENSORY_WAVE_SIZE..(t + 1) * SENSORY_WAVE_SIZE];
        wave_record::write_row(&mut out, row, intent).expect("writing to a Vec cannot fail");
    }
    out
}

/// Regenerates `tests/fixtures/sensitivity_synthetic_cpu.uwav`. Ignored by default —
/// it writes into the source tree, which a normal test run must never do.
#[test]
#[ignore = "writes into the source tree; run with --ignored to regenerate the fixture"]
fn regenerate_the_committed_fixture() {
    std::fs::create_dir_all("tests/fixtures").expect("fixtures directory");
    let mut f = std::fs::File::create(FIXTURE).expect("create fixture");
    f.write_all(&build_fixture_bytes()).expect("write fixture");
    println!("wrote {FIXTURE}");
    save_genome(&Genome::random(FIXTURE_SEED), GENOME_FIXTURE).expect("write genome fixture");
    println!("wrote {GENOME_FIXTURE}");
}

#[test]
fn the_committed_genome_fixture_is_the_seeded_genome() {
    let loaded = load_genome(GENOME_FIXTURE).expect("genome fixture is committed");
    let expected = Genome::random(FIXTURE_SEED);
    assert_eq!(loaded.l1, expected.l1);
    assert_eq!(loaded.l2, expected.l2);
    assert_eq!(loaded.slow, expected.slow);
    assert_eq!(loaded.tau, expected.tau);
    assert_eq!(loaded.gates_w, expected.gates_w);
}

#[test]
fn the_committed_fixture_matches_the_generator() {
    // "Generated by code" has to be checkable, otherwise the committed blob drifts into
    // being a blob nobody can reproduce.
    let on_disk = std::fs::read(FIXTURE).expect("fixture is committed; see this file's header");
    assert_eq!(
        on_disk,
        build_fixture_bytes(),
        "the fixture and its generator disagree — regenerate with \
         `cargo test --release --test sensitivity_gate -- --ignored`"
    );
}

#[test]
fn the_fixture_is_a_readable_uwav_recording() {
    let (waves, intents, cfg) = wave_record::read_all(FIXTURE).expect("UWAV v1 header + rows");
    assert_eq!(intents.len(), FIXTURE_TICKS);
    assert_eq!(waves.len(), FIXTURE_TICKS * SENSORY_WAVE_SIZE);
    assert_eq!(cfg.dt, 1.0 / 64.0);
    assert_eq!(
        cfg.pilot_active, 0,
        "read_all rejects pilot-driven recordings"
    );
}

#[test]
fn replaying_the_fixture_genome_reproduces_the_fixture_commands() {
    // The replay is the one moving part the whole gate rests on: every row of the matrix
    // is a difference between two of its traces. If it ever drifts — a changed default
    // in `SovereignEngine`, a process-global champion leaking in — this fails first and
    // names the cause, instead of the matrix quietly filling with noise.
    let (waves, intents, cfg) = wave_record::read_all(FIXTURE).expect("fixture reads");
    let genome = Genome::random(FIXTURE_SEED);
    let trace = replay_open_loop(&genome, &waves, cfg.dt);
    assert_eq!(trace, intents, "the CPU replay is no longer bit-identical");
}

#[test]
fn the_matrix_has_one_row_per_gene_group() {
    // The acceptance criterion C3 asks for in so many words.
    let (waves, _intents, cfg) = wave_record::read_all(FIXTURE).expect("fixture reads");
    let genome = Genome::random(FIXTURE_SEED);
    let report = run_gate(&genome, &waves, cfg.dt, &DEFAULT_DELTAS).expect("well-formed wave");

    let declared: Vec<&str> = groups().iter().map(|g| g.name).collect();
    let printed: Vec<&str> = report.rows.iter().map(|r| r.name).collect();
    assert_eq!(
        printed, declared,
        "one row per group, in the genome's disk order"
    );
    assert_eq!(report.ticks, FIXTURE_TICKS);

    // The matrix must also be printable — it is the artefact a human reads.
    let text = format!("{report}");
    for name in &declared {
        assert!(
            text.contains(name),
            "row for '{name}' is missing from the table"
        );
    }
    assert!(
        text.contains("off-path"),
        "off-path reasons are printed under the table"
    );
}

#[test]
fn the_gate_passes_on_the_fixture_genome() {
    // Green means: every block the CPU replay can read moves at least one command, and
    // every block declared off-path stayed silent. A failure here is either a real
    // regression in the brain's wiring or a `groups()` declaration that has gone stale.
    let (waves, _intents, cfg) = wave_record::read_all(FIXTURE).expect("fixture reads");
    let genome = Genome::random(FIXTURE_SEED);
    let report = run_gate(&genome, &waves, cfg.dt, &DEFAULT_DELTAS).expect("well-formed wave");
    let failing: Vec<String> = report
        .failures()
        .iter()
        .map(|r| format!("{} ({:?})", r.name, r.verdict))
        .collect();
    assert!(
        report.passed(),
        "gate failed for: {}\n{report}",
        failing.join(", ")
    );
    // And it is not green by vacuum: the two positive controls really did move.
    for name in ["l1", "l2", "tau"] {
        let row = report.rows.iter().find(|r| r.name == name).unwrap();
        assert_eq!(row.verdict, Verdict::Moved, "{name} must reach the command");
    }
}

#[test]
fn a_genome_from_disk_gives_the_same_matrix_as_the_one_in_memory() {
    // The binary reads its genome with `gpu::genome_io::load_genome`, the canonical
    // parser (`genome_io.rs:1-5` — a duplicate parser in `genoma_view` once read
    // `neuron_activation` believing it was τ). This checks the gate is indifferent to
    // the round trip, i.e. that nothing the matrix depends on is lost on disk.
    let dir = std::env::temp_dir().join(format!("sens_gate_{}", std::process::id()));
    std::fs::create_dir_all(&dir).expect("scratch dir");
    let path = dir.join("fixture.bin");
    let path_str = path.to_str().expect("utf-8 path").to_string();

    let genome = Genome::random(FIXTURE_SEED);
    save_genome(&genome, &path_str).expect("save");
    let reloaded = load_genome(&path_str).expect("load");
    let _ = std::fs::remove_dir_all(&dir);

    let (waves, _intents, cfg) = wave_record::read_all(FIXTURE).expect("fixture reads");
    let a = run_gate(&genome, &waves, cfg.dt, &[0.5]).expect("in-memory");
    let b = run_gate(&reloaded, &waves, cfg.dt, &[0.5]).expect("from disk");
    for (ra, rb) in a.rows.iter().zip(b.rows.iter()) {
        assert_eq!(ra.name, rb.name);
        assert_eq!(
            ra.verdict, rb.verdict,
            "verdict for '{}' changed on disk",
            ra.name
        );
        assert_eq!(
            ra.peak_abs_delta, rb.peak_abs_delta,
            "deltas for '{}' changed on disk",
            ra.name
        );
    }
}

#[test]
fn the_fixture_genome_reports_the_degrees_of_freedom_of_each_block() {
    // `dof` is the other C3 ruler the binary prints next to the matrix; this pins the
    // two together so the header line cannot go stale against the module.
    let genome = Genome::random(FIXTURE_SEED);
    let by_block = dof_by_block(&genome, DEFAULT_GENE_THRESHOLD);
    let names: Vec<&str> = by_block.iter().map(|(n, _)| *n).collect();
    assert_eq!(names, vec!["slow", "tau", "gates_w"]);
    let gates = by_block.iter().find(|(n, _)| *n == "gates_w").unwrap().1;
    assert_eq!(
        gates, 0,
        "M4 gates are born neutral at 0.0 (evolution.rs:556)"
    );
}
