/// Laws derived from the IARA ecosystem — search cost and metabolism.
///
/// Documented in MATH_INVENTORY.md (F27, F28) and empirically confirmed
/// in the iara-agua and Universe projects.
///
/// - `search_noise_threshold` (Prospecting Law / "Lei do Garimpo"): expected threshold of
///   the best of M samples of pure noise; a fitness gain is only "real" if it exceeds it.
/// - `aic_cost` (AIC/metabolism): Akaike penalty based on the residual variance.
/// - `ric_penalty` (RIC): Bayesian variant of the Prospecting Law used in network pruning.

/// Prospecting threshold: expected gain of the best of M samples of N(0, σ²) noise.
///
/// Formula: `σ · √(2 · ln M)`
///
/// Interpretation: if we pick the best of M candidates generated by pure Gaussian
/// noise N(0, σ²), the expected value of the maximum is `σ·√(2·ln M)`. A fitness
/// gain only beats the stochastic-search ceiling if it exceeds this threshold.
///
/// Returns 0.0 if `sigma <= 0` or `m_alternatives <= 1`.
///
/// Canonical source of this function (E1 extracts it from brain_capacity.rs).
pub fn search_noise_threshold(sigma: f32, m_alternatives: usize) -> f32 {
    if sigma <= 0.0 || m_alternatives <= 1 {
        return 0.0;
    }
    sigma * (2.0 * (m_alternatives as f32).ln()).sqrt()
}

/// AIC cost — simplified Akaike information criterion.
///
/// Formula: `AIC ≈ n_samples · ln(residual_variance) + 2 · n_params`
///
/// Minimizing AIC penalizes models with more parameters that do not sufficiently
/// reduce the residual variance. Used as "metabolism" in the law
/// `met_c = σ²(1 + 2·dof/N)` from the iara-agua project.
///
/// This function returns the per-sample (normalized) cost: `ln(σ²) + 2k/N`
/// where `k = n_params` and `N = n_samples`.
///
/// Returns 0.0 if `residual_variance <= 0` or `n_samples == 0`.
pub fn aic_cost(residual_variance: f32, n_params: usize, n_samples: usize) -> f32 {
    if residual_variance <= 0.0 || n_samples == 0 {
        return 0.0;
    }
    residual_variance.ln() + 2.0 * n_params as f32 / n_samples as f32
}

/// RIC penalty — Bayesian variant of the Prospecting Law.
///
/// Formula: `σ · √(2 · ln M)` (same as search_noise_threshold).
///
/// RIC (Risk Inflation Criterion) penalizes variable/neuron selection by the
/// expected cost of picking the best of M random alternatives. It is the
/// generalization of the Deflated Sharpe Ratio to neuron selection.
///
/// In network pruning: a neuron only justifies existing if its gain > ric_penalty.
///
/// Identical to the `search_noise_threshold` formula — kept as a semantic alias
/// to make the pruning vs. evolutionary-search context clear.
pub fn ric_penalty(sigma: f32, m_alternatives: usize) -> f32 {
    search_noise_threshold(sigma, m_alternatives)
}

// ---------------------------------------------------------------------------
// Unit tests
