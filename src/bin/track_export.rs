//! lab-ui PRD S2 — exports the track (`track.json`, PRD §5) for one `(seed, width)`
//! pair: seed, lap_m, width_m, waypoints, and the voxel grid as run-length rows.
//!
//! Reuses `universe::world::VoxelWorld::new`, the SAME constructor `pista_check`
//! (`src/bin/pista_check.rs`) and the real simulator use to build the track -- this
//! binary does not regenerate track geometry by a second method, it reads the same
//! `VoxelWorld.grid`/`waypoints_world`/`lap_distance` fields `pista_check` walks.
//!
//! CPU-only: `VoxelWorld::new` builds plain Rust data (a `Vec<VoxelType>` grid and a
//! waypoint list) -- no `wgpu` device, no Bevy `App`, no window. It imports
//! `bevy::prelude::*` only for `Vec2`/`Vec3` math types and the `#[derive(Resource)]` on
//! an unrelated wrapper struct this binary never touches.
//!
//! Usage:
//!   track_export <seed> <width_m> <out.json>

use serde_json::json;
use std::io::Write as _;

use universe::world::{VoxelType, VoxelWorld};

/// Run-length-encodes one grid row as `[material_id, run_length]` pairs.
fn rle_row(row: &[VoxelType]) -> Vec<[u32; 2]> {
    let mut out = Vec::new();
    let mut i = 0;
    while i < row.len() {
        let material = row[i] as u32;
        let mut j = i + 1;
        while j < row.len() && row[j] as u32 == material {
            j += 1;
        }
        out.push([material, (j - i) as u32]);
        i = j;
    }
    out
}

fn build_track_json(seed: u64, width: f32) -> serde_json::Value {
    let world = {
        let _quiet = universe::world::silence_map_diag();
        VoxelWorld::new(seed, width)
    };

    let waypoints: Vec<[f32; 2]> = world.waypoints_world.iter().map(|p| [p.x, p.y]).collect();

    let size = world.size;
    let rows: Vec<Vec<[u32; 2]>> = (0..size)
        .map(|row_idx| {
            let start = row_idx * size;
            rle_row(&world.grid[start..start + size])
        })
        .collect();

    json!({
        "schema_version": 1,
        "seed": seed,
        "width_m": width,
        "lap_m": world.lap_distance,
        "cell_size_m": world.cell_size,
        "grid_cells": size,
        "grid_extent_m": size as f32 * world.cell_size,
        "waypoints": waypoints,
        "waypoints_note": "world.waypoints_world (x,z), the same field pista_check.rs walks to report axis/width/radius. NOT resampled.",
        "materials": {"0": "grass", "1": "road", "2": "wall", "3": "hole"},
        "voxel_grid_rle": {
            "rows": size,
            "cols": size,
            "row_major": true,
            "note": "world.grid, row-major (row = z index, col = x index, cell = row*cols+col in the source Vec<VoxelType>), each row run-length-encoded as [material_id, run_length] pairs. World position of cell (row,col) = (col*cell_size_m, row*cell_size_m).",
            "data": rows,
        },
        "source": "universe::world::VoxelWorld::new(seed, width) -- the same constructor pista_check.rs and the simulator use; not regenerated by a second method.",
    })
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    if args.len() != 4 {
        eprintln!("usage: track_export <seed> <width_m> <out.json>");
        std::process::exit(2);
    }
    let seed: u64 = args[1].parse().unwrap_or_else(|e| {
        eprintln!("track_export: invalid seed {:?}: {e}", args[1]);
        std::process::exit(2);
    });
    let width: f32 = args[2].parse().unwrap_or_else(|e| {
        eprintln!("track_export: invalid width_m {:?}: {e}", args[2]);
        std::process::exit(2);
    });
    let out_path = &args[3];

    let out = build_track_json(seed, width);

    let mut f = std::fs::File::create(out_path).unwrap_or_else(|e| {
        eprintln!("track_export: cannot create {out_path}: {e}");
        std::process::exit(1);
    });
    let text = serde_json::to_string(&out).expect("serialize track.json");
    f.write_all(text.as_bytes()).expect("write track.json");
    println!(
        "track_export: wrote {out_path} (seed {seed}, width {width}m, lap {:.1}m, {} waypoints)",
        out["lap_m"].as_f64().unwrap_or(0.0),
        out["waypoints"].as_array().map(|a| a.len()).unwrap_or(0)
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rle_row_round_trips_and_sums_to_row_length() {
        let row = vec![
            VoxelType::Grass, VoxelType::Grass, VoxelType::Road, VoxelType::Road, VoxelType::Road, VoxelType::Wall,
        ];
        let encoded = rle_row(&row);
        assert_eq!(encoded, vec![[0, 2], [1, 3], [2, 1]]);
        let total: u32 = encoded.iter().map(|pair| pair[1]).sum();
        assert_eq!(total as usize, row.len());
    }

    #[test]
    fn rle_row_handles_a_single_uniform_row() {
        let row = vec![VoxelType::Grass; 320];
        let encoded = rle_row(&row);
        assert_eq!(encoded, vec![[0, 320]]);
    }

    #[test]
    fn build_track_json_has_a_road_axis_and_waypoints_for_a_real_seed() {
        // Same seed the S0 fixture's source run used (world_seed 8005, standard width).
        let out = build_track_json(8005, 28.0);
        let waypoints = out["waypoints"].as_array().expect("waypoints array");
        assert!(!waypoints.is_empty(), "a real track must have waypoints");
        assert!(out["lap_m"].as_f64().unwrap() > 0.0);
        let rows = out["voxel_grid_rle"]["data"].as_array().expect("rows");
        assert_eq!(rows.len(), out["grid_cells"].as_u64().unwrap() as usize);
        // At least one row must contain a Road run (material id 1) -- otherwise the grid
        // export would be silently disconnected from the actual track.
        let has_road = rows.iter().any(|row| {
            row.as_array()
                .unwrap()
                .iter()
                .any(|pair| pair.as_array().unwrap()[0].as_u64() == Some(1))
        });
        assert!(has_road, "expected at least one Road-material run in the voxel grid");
    }
}
